import { jsPDF } from "jspdf";

export function downloadPrescriptionPdf({
  id,
  patientName,
  doctorName,
  date,
  medicines,
  advice,
  followUp,
}) {
  const doc = new jsPDF();
  let y = 20;

  // Writes text, wraps long lines, starts a new page if needed
  const addLine = (text, size = 11, bold = false) => {
    doc.setFontSize(size);
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.splitTextToSize(text, 170).forEach((line) => {
      if (y > 275) {
        doc.addPage();
        y = 20;
      }
      doc.text(line, 20, y);
      y += size * 0.5 + 2;
    });
  };

  // Header
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text("St Eves Clinic", 105, y, { align: "center" });
  y += 6;
  doc.line(20, y, 190, y);
  y += 10;

  addLine("PRESCRIPTION", 14, true);
  y += 2;
  addLine(`Patient: ${patientName}`);
  addLine(`Visit date: ${date}`);
  addLine(`Doctor: ${doctorName}`);
  y += 6;

  // Medicines
  addLine("Medicines", 13, true);
  medicines.forEach((m, i) => {
    addLine(`${i + 1}. ${m.name}${m.dose ? " - " + m.dose : ""}`, 11, true);
    const how = [m.frequency, m.days ? `for ${m.days} days` : ""]
      .filter(Boolean)
      .join(" ");
    if (how) addLine(`    ${how}`);
  });

  if (advice) {
    y += 6;
    addLine("Advice", 13, true);
    addLine(advice);
  }
  if (followUp) {
    y += 6;
    addLine("Follow-up", 13, true);
    addLine(followUp);
  }

  y += 12;
  addLine("Generated by St Eves (portfolio demo, not a real prescription).", 9);

  doc.save(`prescription-${id}.pdf`);
}